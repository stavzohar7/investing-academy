function partOfLevel(levelId) { return PARTS.find(p => p.levels.includes(levelId)); }
function partProgress(p) {
  const lessons = p.levels.flatMap(id => (window.CURRICULUM.find(l => l.id === id) || { lessons: [] }).lessons);
  const done = lessons.filter(x => x.id in State.data.done).length;
  return { done, total: lessons.length, pct: lessons.length ? done / lessons.length : 0 };
}
