  const locate = id => { for (const lv of C) { const i = lv.lessons.findIndex(x => x.id === id); if (i >= 0) return { lv, i }; } return null; };
  const LET = ["א", "ב", "ג", "ד"];
  MODULES.forEach(([ids, title, practical]) => {
    const t = locate(ids[0]); if (!t) return;
    const T = t.lv.lessons[t.i];
    const members = ids.map(id => { const l = locate(id); return l && l.lv.lessons[l.i]; });
    if (members.some(m => !m)) return;
    const n = members.length;
    T.parts = ids.slice();
    T.minutes = members.reduce((s, m) => s + (m.minutes || 0), 0);
    T.body = members.map((m, k) => `<h3>חלק ${LET[k]}׳ — ${m.title}</h3>\n` + m.body).join("\n<hr>\n");
    T.takeaways = members.flatMap(m => m.takeaways.slice(0, Math.ceil(8 / n))).slice(0, 9);
    T.quiz = members.flatMap(m => m.quiz.slice(0, n === 2 ? 3 : 2));
    T.practical = practical;
    T.title = title;
    ids.slice(1).forEach(aid => {
      const a = locate(aid); a.lv.lessons.splice(a.i, 1);
      window.LESSON_ALIAS[aid] = ids[0];
    });
  });

