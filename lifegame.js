const lifeLoad = () => { try { return JSON.parse(localStorage.getItem("ia-lifegame")) || {}; } catch (e) { return {}; } };
const lifeSave = d => { try { localStorage.setItem("ia-lifegame", JSON.stringify(d)); } catch (e) { /* ignore */ } };

Routes.lifegame = function () {
  const done = lifeLoad();
  const left = LIFE_SCENARIOS.filter(x => !(x.id in done));
  const pts = Object.values(done).reduce((a, b) => a + b, 0), max = Object.keys(done).length * 2;
  const head = `<h1>🎲 תרחישי חיים</h1>
    <p class="muted">החלטות כסף שצעירים נתקלים בהן באמת. בוחרים תשובה, ומקבלים הסבר. אין כאן "ציון בית ספרי": המטרה היא לחדד את העקרונות לפני שהמצב אמיתי. התשובות המומלצות הן לפי עקרונות הלימוד באתר, והן אינן ייעוץ אישי.</p>
    <p class="small" aria-live="polite">${Object.keys(done).length} מתוך ${LIFE_SCENARIOS.length} תרחישים${max ? ` · התאמה לעקרונות: ${pts} מתוך ${max}` : ""}</p>`;
  if (!left.length) {
    app().innerHTML = `${head}<section class="card"><h2>סיימתם את כל התרחישים 🎉</h2><p>התאמה לעקרונות הלימוד: <b>${pts} מתוך ${max}</b>. אפשר להתחיל מחדש ולנסות תשובות אחרות, או להמשיך ל<a href="#charter">חוקה האישית שלכם</a>.</p><div class="row mt"><button type="button" class="btn" id="lgReset">התחלה מחדש</button></div></section>`;
    document.getElementById("lgReset").onclick = () => { lifeSave({}); Routes.lifegame(); };
    return;
  }
  const sc = left[0];
  app().innerHTML = `${head}<section class="card" aria-labelledby="lgT"><h2 id="lgT">${esc(sc.t)}</h2><p>${esc(sc.q)}</p>
    <div id="lgOpts">${sc.o.map((o, i) => [o, i]).sort(() => Math.random() - 0.5).map(([o, i]) => `<button type="button" class="choice lg-opt" data-i="${i}" style="display:block;width:100%;text-align:right;margin:6px 0"><span><b>${esc(o[0])}</b></span></button>`).join("")}</div>
    <div id="lgFb" aria-live="polite"></div></section>`;
  document.querySelectorAll(".lg-opt").forEach(b => b.onclick = () => {
    const o = sc.o[+b.dataset.i];
    const best = sc.o.find(x => x[1] === 2);
    document.querySelectorAll(".lg-opt").forEach(x => { x.disabled = true; });
    const tag = o[1] === 2 ? "✅ תואם לעקרונות הלימוד" : o[1] === 1 ? "🟡 אפשרי, עם הסתייגות" : "🔴 סיכון";
    done[sc.id] = o[1]; lifeSave(done);
    document.getElementById("lgFb").innerHTML = `<div class="box mt"><b>${tag}</b><p>${esc(o[2])}</p>${o[1] !== 2 ? `<p><b>הכיוון המומלץ:</b> ${esc(best[0])}. ${esc(best[2])}</p>` : ""}
      <p class="small">להמשך: <a href="${sc.link[0]}">${esc(sc.link[1])}</a></p><div class="row mt"><button type="button" class="btn" id="lgNext">התרחיש הבא ←</button></div></div>`;
    document.getElementById("lgNext").focus();
    document.getElementById("lgNext").onclick = () => Routes.lifegame();
  });
};
